from pathlib import Path

from pypdf import PdfReader, PdfWriter
from pypdf.generic import DecodedStreamObject, NameObject


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "output/pdf/WMS365_BOL_ORD-001340_REVISED_KG.pdf"
OUTPUT = ROOT / "output/pdf/WMS365_BOL_ORD-001340_REVISED_KG_2DP.pdf"
REPLACEMENTS = {
    b"(1,048.3 KG)": b"(1,048.25 KG)",
    b"(1,048.7 KG)": b"(1,048.71 KG)",
    b"(1,049.2 KG)": b"(1,049.16 KG)",
    b"(1,047.8 KG)": b"(1,047.80 KG)",
    b"(4,193.9 KG)": b"(4,193.92 KG)",
}


def main():
    reader = PdfReader(SOURCE)
    if len(reader.pages) != 1:
        raise ValueError("Expected one WMS-generated BOL page")
    writer = PdfWriter()
    writer.clone_document_from_reader(reader)
    page = writer.pages[0]
    data = page.get_contents().get_data()
    for before, after in REPLACEMENTS.items():
        if data.count(before) != 1:
            raise ValueError(f"Expected one system-rendered weight: {before!r}")
        data = data.replace(before, after)
    stream = DecodedStreamObject()
    stream.set_data(data)
    page[NameObject("/Contents")] = writer._add_object(stream)
    writer.add_metadata({
        "/Title": "Revised BOL ORD-001340 - kilogram weights and item MS26062403",
        "/Subject": "Pre-shipment, unsigned BOL generated by WMS365; display weights formatted to two decimals",
    })
    with OUTPUT.open("wb") as target:
        writer.write(target)

    verified = PdfReader(OUTPUT)
    text = verified.pages[0].extract_text()
    for expected in ("MS26062403", "DI34AA", "DI14AB", "DI16AB", "DI28AA",
                     "1,048.25 KG", "1,048.71 KG", "1,049.16 KG", "1,047.80 KG", "4,193.92 KG"):
        if expected not in text:
            raise ValueError(f"Final PDF missing {expected}")
    if "MS26060402G" in text:
        raise ValueError("Final BOL still displays the WMS source SKU")
    print(OUTPUT)


if __name__ == "__main__":
    main()
